const mongoose = require("mongoose");

// ==========================================================
// CART ITEM SCHEMA
// ==========================================================

const cartItemSchema = new mongoose.Schema(
  {
    // ------------------------------------------------------
    // PRODUCT
    // ------------------------------------------------------

    product: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Product",
      required: true,
    },

    // ------------------------------------------------------
    // PRODUCT VARIANT
    // ------------------------------------------------------

    variant: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "ProductVariant",
      required: true,
    },

    // ------------------------------------------------------
    // QUANTITY
    // ------------------------------------------------------

    quantity: {
      type: Number,
      required: true,
      min: 1,
      default: 1,
    },

    // ------------------------------------------------------
    // PRICE AT THE TIME OF ADDING
    // ------------------------------------------------------

    price: {
      type: Number,
      required: true,
      min: 0,
    },

    // ------------------------------------------------------
    // PRODUCT NAME SNAPSHOT
    // ------------------------------------------------------

    productName: {
      type: String,
      required: true,
      trim: true,
    },

    // ------------------------------------------------------
    // PRODUCT IMAGE SNAPSHOT
    // ------------------------------------------------------

    image: {
      type: String,
      default: "",
    },

    // ------------------------------------------------------
    // SIZE SNAPSHOT
    // ------------------------------------------------------

    size: {
      type: String,
      default: "",
      trim: true,
    },

    // ------------------------------------------------------
    // COLOR SNAPSHOT
    // ------------------------------------------------------

    color: {
      type: String,
      default: "",
      trim: true,
    },
  },
  {
    _id: true,
  }
);

// ==========================================================
// CART SCHEMA
// ==========================================================

const cartSchema = new mongoose.Schema(
  {
    // ------------------------------------------------------
    // USER
    // ------------------------------------------------------

    user: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
      unique: true,
      index: true,
    },

    // ------------------------------------------------------
    // CART ITEMS
    // ------------------------------------------------------

    items: {
      type: [cartItemSchema],
      default: [],
    },

    // ------------------------------------------------------
    // TOTAL ITEMS
    // ------------------------------------------------------

    totalItems: {
      type: Number,
      default: 0,
      min: 0,
    },

    // ------------------------------------------------------
    // TOTAL AMOUNT
    // ------------------------------------------------------

    totalAmount: {
      type: Number,
      default: 0,
      min: 0,
    },

    // ------------------------------------------------------
    // CART STATUS
    // ------------------------------------------------------

    status: {
      type: String,
      enum: ["active", "ordered", "abandoned"],
      default: "active",
    },
  },
  {
    timestamps: true,
  }
);

// ==========================================================
// EXPORT
// ==========================================================

module.exports = mongoose.model("Cart", cartSchema);